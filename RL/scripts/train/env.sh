#!/usr/bin/env bash
# Environment defaults for Open-o3-Video-v2 GRPO training.

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
MASTER_PORT="${MASTER_PORT:-29500}"
MASTER_ADDR="${MASTER_ADDR:-127.0.0.1}"
NODE_RANK="${NODE_RANK:-0}"
NNODES="${NNODES:-1}"
NPROC_PER_NODE="${NPROC_PER_NODE:-8}"
WANDB_MODE="${WANDB_MODE:-disabled}"
OUT_CKPT_ROOT="${OUT_CKPT_ROOT:-${REPO_ROOT}/checkpoints}"
CACHE_ROOT="${CACHE_ROOT:-${REPO_ROOT}/.cache}"
WANDB_DIR="${WANDB_DIR:-${CACHE_ROOT}/wandb}"
WANDB_ARTIFACT_DIR="${WANDB_ARTIFACT_DIR:-${CACHE_ROOT}/wandb_artifacts}"
TMPDIR="${TMPDIR:-${REPO_ROOT}/.cache/tmp}"
HYDRA_FULL_ERROR="${HYDRA_FULL_ERROR:-1}"
VLLM_USE_V1="${VLLM_USE_V1:-1}"
DATA_MODE="${DATA_MODE:-multi_image}"
UNIFIED_TRAIN_MAX_SAMPLES="${UNIFIED_TRAIN_MAX_SAMPLES:-12800}"
UNIFIED_TRAIN_MAX_SAMPLES_RANDOM="${UNIFIED_TRAIN_MAX_SAMPLES_RANDOM:-true}"
UNIFIED_TRAIN_MAX_SAMPLES_SEED="${UNIFIED_TRAIN_MAX_SAMPLES_SEED:-111}"

export REPO_ROOT MASTER_PORT MASTER_ADDR NODE_RANK NNODES NPROC_PER_NODE
export WANDB_MODE OUT_CKPT_ROOT CACHE_ROOT WANDB_DIR WANDB_ARTIFACT_DIR
export TMPDIR HYDRA_FULL_ERROR VLLM_USE_V1 DATA_MODE
export UNIFIED_TRAIN_MAX_SAMPLES UNIFIED_TRAIN_MAX_SAMPLES_RANDOM UNIFIED_TRAIN_MAX_SAMPLES_SEED

if [[ -f "${REPO_ROOT}/scripts/train/env.local.sh" ]]; then
  # shellcheck disable=SC1091
  source "${REPO_ROOT}/scripts/train/env.local.sh"
fi
